"""Core data model: tasks, agent trajectories, grader verdicts, ground-truth labels.

Every trajectory and label carries a `Provenance`. Certification results are only
*reportable* when the labels came from humans (or an external benchmark's own labels)
AND the trajectories came from a real agent or benchmark. Synthetic and stub data can
exercise the pipeline but can never certify a grader. This is enforced in `certify`,
not left to discipline.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Any, Literal

from pydantic import BaseModel, Field


class Provenance(StrEnum):
    SYNTHETIC = "synthetic"  # generated by certharness templates for development
    STUB = "stub"  # hand-written test scaffolding
    AGENT_RUN = "agent_run"  # trajectory produced by actually running an agent
    HUMAN = "human"  # label assigned by a human rater
    EXTERNAL = "external"  # trajectory/label imported from a public benchmark


REPORTABLE_LABELS = frozenset({Provenance.HUMAN, Provenance.EXTERNAL})
REPORTABLE_TRAJECTORIES = frozenset({Provenance.AGENT_RUN, Provenance.EXTERNAL})


class ToolCall(BaseModel):
    id: str
    name: str
    args: dict[str, Any] = Field(default_factory=dict)


class Step(BaseModel):
    """One message in a trajectory.

    assistant steps may carry tool_calls; tool steps answer exactly one call via
    tool_call_id and may be marked is_error.
    """

    role: Literal["user", "assistant", "tool"]
    content: str = ""
    tool_calls: list[ToolCall] = Field(default_factory=list)
    tool_call_id: str | None = None
    is_error: bool = False


class ExpectedCall(BaseModel):
    """A tool call the task requires. `args` is a required subset, not an exact match."""

    name: str
    args: dict[str, Any] = Field(default_factory=dict)


class Task(BaseModel):
    id: str
    instruction: str
    tools: list[str]
    expected_calls: list[ExpectedCall] = Field(default_factory=list)
    forbidden_tools: list[str] = Field(default_factory=list)
    expected_final: str | None = None  # regex the final answer must match
    metadata: dict[str, Any] = Field(default_factory=dict)


class Mutation(BaseModel):
    """Record of the seeded fault planted in a mutant trajectory."""

    operator: str
    severity: Literal["critical", "major"]
    tier: Literal["obvious", "subtle"]
    parent_id: str
    seed: int
    step_index: int | None = None
    detail: str = ""


class Trajectory(BaseModel):
    id: str
    task: Task
    steps: list[Step]
    provenance: Provenance
    source: str | None = None  # e.g. "synthetic:toy-v1", "external:tau-bench"
    mutation: Mutation | None = None

    @property
    def final_answer(self) -> str | None:
        """Content of the last assistant step that makes no tool calls."""
        for step in reversed(self.steps):
            if step.role == "assistant" and not step.tool_calls:
                return step.content
        return None

    def tool_calls(self) -> list[tuple[int, ToolCall]]:
        """All tool calls in order, with the index of the step that made them."""
        return [
            (i, c) for i, s in enumerate(self.steps) if s.role == "assistant" for c in s.tool_calls
        ]

    def result_index(self, call_id: str) -> int | None:
        for i, s in enumerate(self.steps):
            if s.role == "tool" and s.tool_call_id == call_id:
                return i
        return None

    def blinded(self) -> Trajectory:
        """Copy with mutation metadata removed, for handing to a grader."""
        return self.model_copy(update={"mutation": None})


class Verdict(BaseModel):
    trajectory_id: str
    grader: str
    passed: bool
    score: float | None = None
    reasons: list[str] = Field(default_factory=list)


class Label(BaseModel):
    """Ground truth for one trajectory. `rater`/`session` support intra-rater analysis."""

    trajectory_id: str
    passed: bool
    provenance: Provenance
    rater: str | None = None
    session: int | None = None
    note: str = ""
